#!/bin/sh
# Passe-plat standalone installer. Generated from the machine-side distribution.
# Download this file, then run: sh passe-plat-install.sh
# The payload includes the machine scripts; no Git checkout or package manager is needed.

pp_boot_error() { printf '[%s] %s\n' "$1" "$2" >&2; exit 1; }
pp_boot_help() {
    cat <<'HELP'
Passe-plat — installation de la machine

  sh passe-plat-install.sh                  installation interactive, puis QR d'appairage
  sh passe-plat-install.sh --yes            choix par défaut
  sh passe-plat-install.sh --dry-run        diagnostic des prérequis
  sh passe-plat-install.sh --extract-to DIR extraire les scripts pour les lire, sans les installer

macOS et Linux avec un shell POSIX. Aucun Homebrew requis ou exécuté.
L'installation conserve les appairages et la configuration déjà présents.
HELP
}
case "${1:-}" in -h|--help) pp_boot_help; exit 0 ;; esac
case "$(uname -s)" in Darwin|Linux) ;; *) pp_boot_error PP_INSTALL_PLATFORM_UNSUPPORTED 'This installer requires macOS or Linux with a POSIX shell.' ;; esac
for pp_boot_tool in base64 tar gzip mktemp awk; do
    command -v "$pp_boot_tool" >/dev/null 2>&1 || pp_boot_error PP_INSTALL_TOOL_MISSING "Required system utility is missing: $pp_boot_tool"
done
[ -f "$0" ] || pp_boot_error PP_INSTALL_FILE_REQUIRED 'Download the installer to a file, then run it with sh. Interactive installation requires standard input.'
pp_boot_tmp=$(mktemp -d "${TMPDIR:-/tmp}/passe-plat-install.XXXXXX") || exit 1
trap 'rm -rf "$pp_boot_tmp"' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
umask 077
awk 'found { print } /^__PASSE_PLAT_ARCHIVE__$/ { found=1 }' "$0" > "$pp_boot_tmp/payload.b64"
if printf 'aGk=' | base64 -d >/dev/null 2>&1; then pp_boot_decode=-d; else pp_boot_decode=-D; fi
base64 "$pp_boot_decode" < "$pp_boot_tmp/payload.b64" > "$pp_boot_tmp/payload.tar.gz" \
    || pp_boot_error PP_INSTALL_PAYLOAD_INVALID 'The installer payload could not be decoded. Download the installer again.'
if command -v shasum >/dev/null 2>&1; then
    pp_boot_hash=$(shasum -a 256 "$pp_boot_tmp/payload.tar.gz" | awk '{print $1}')
elif command -v sha256sum >/dev/null 2>&1; then
    pp_boot_hash=$(sha256sum "$pp_boot_tmp/payload.tar.gz" | awk '{print $1}')
else
    pp_boot_error PP_INSTALL_CHECKSUM_TOOL_MISSING 'A SHA-256 utility is required: shasum or sha256sum.'
fi
[ "$pp_boot_hash" = '1cfcf38ec675f9418c424f93ae28b26cf52b0c4e8789e17d93ae4bc8c87b2a8f' ] \
    || pp_boot_error PP_INSTALL_CHECKSUM_MISMATCH 'The installer payload checksum does not match. Download the installer again.'
mkdir "$pp_boot_tmp/source" || exit 1
tar -xzf "$pp_boot_tmp/payload.tar.gz" -C "$pp_boot_tmp/source" \
    || pp_boot_error PP_INSTALL_EXTRACT_FAILED 'The installer payload could not be extracted.'
if [ "${1:-}" = --extract-to ]; then
    [ "$#" -eq 2 ] && [ -n "$2" ] || pp_boot_error PP_INSTALL_ARGUMENTS_INVALID 'Expected --extract-to and one destination directory.'
    [ ! -e "$2" ] || pp_boot_error PP_INSTALL_DESTINATION_EXISTS 'The extraction destination already exists. Choose a new directory.'
    mkdir -p "$2" && cp -R "$pp_boot_tmp/source/." "$2/" || exit 1
    printf 'Scripts extraits dans %s ; aucune installation effectuée.\n' "$2"
    exit 0
fi
printf '%s\n' 'Passe-plat — préparation de cette machine' 'Le script vérifie les prérequis, installe Passe-plat, puis affiche le QR à scanner.' >&2
sh "$pp_boot_tmp/source/install.sh" "$@"
pp_boot_status=$?
if [ "$pp_boot_status" -eq 2 ]; then
    printf '\n%s\n' 'Un prérequis manque. Le diagnostic ci-dessus indique lequel.' \
        'Tailscale : https://tailscale.com/download — connecter cette machine au même réseau que le téléphone.' \
        'tmux : https://github.com/tmux/tmux-builds/releases — binaires précompilés pour macOS et Linux.' \
        'SSH sur macOS : Réglages Système > Général > Partage > Session à distance.' \
        'SSH sur Linux : activer le serveur OpenSSH de la distribution.' \
        'Relancer ce même script après la préparation ; les paramètres existants sont conservés.' >&2
fi
exit "$pp_boot_status"
